import type { RequestHandler } from "express";

import { ApiError } from "../lib/http/api-error.js";
import { prisma } from "../lib/prisma.js";
import {
  hashSessionToken,
  SESSION_COOKIE_NAME,
} from "../modules/auth/session.js";

export interface AuthenticatedUser {
  id: string;
  name: string;
  email: string;
  sessionId: string;
}

function getSessionToken(cookieHeader: string | undefined): string | null {
  if (!cookieHeader) {
    return null;
  }

  const matchingCookies = cookieHeader
    .split(";")
    .map((cookie) => cookie.trim())
    .filter((cookie) => {
      const separatorIndex = cookie.indexOf("=");

      if (separatorIndex === -1) {
        return false;
      }

      return cookie.slice(0, separatorIndex).trim() === SESSION_COOKIE_NAME;
    });

  // Reject duplicate session cookies to avoid ambiguous authentication.
  if (matchingCookies.length !== 1) {
    return null;
  }

  const separatorIndex = matchingCookies[0]!.indexOf("=");
  const token = matchingCookies[0]!.slice(separatorIndex + 1).trim();

  // Tokens generated by randomBytes(32).toString("base64url")
  // contain exactly 43 URL-safe characters.
  if (!/^[A-Za-z0-9_-]{43}$/.test(token)) {
    return null;
  }

  return token;
}

export const authenticateSession: RequestHandler = async (req, res, next) => {
  try {
    const sessionToken = getSessionToken(req.headers.cookie);

    if (!sessionToken) {
      throw new ApiError(401, "UNAUTHENTICATED", "Authentication is required.");
    }

    const tokenHash = hashSessionToken(sessionToken);

    const session = await prisma.session.findUnique({
      where: { tokenHash },
      select: {
        id: true,
        userId: true,
        expiresAt: true,
        revokedAt: true,
        user: {
          select: {
            id: true,
            name: true,
            email: true,
            status: true,
          },
        },
      },
    });

    if (
      !session ||
      session.revokedAt !== null ||
      session.expiresAt.getTime() <= Date.now() ||
      session.user.status !== "ACTIVE"
    ) {
      throw new ApiError(401, "UNAUTHENTICATED", "Authentication is required.");
    }

    const authenticatedUser: AuthenticatedUser = {
      id: session.user.id,
      name: session.user.name,
      email: session.user.email,
      sessionId: session.id,
    };

    res.locals.authenticatedUser = authenticatedUser;

    return next();
  } catch (error) {
    return next(error);
  }
};
